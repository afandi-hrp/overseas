-- Modul REPORTING (Dashboard + Cost per Vessel) -- tabel master_vessel, fondasi paling awal
-- sebelum tabel alokasi biaya (courier/sea-air/borongan per vessel) dibuat menyusul.
--
-- Sumber data: file "MASTER VESSEL.xlsx" yang dikirim user (3 kolom terisi: UNDER=base,
-- UNDER2=fleet_group, VESSEL NAME=vessel_name -- kolom lain di file itu header kosong template,
-- TIDAK ada data). alias_name/vessel_type/category/status TIDAK ADA di file sumber, diturunkan:
--   - category: fleet_group === 'OTHERS' -> 'OTHERS', selain itu (termasuk fleet_group='TBA',
--     mis. "MT. PERTAMINA GALUNGGUNG" yang armadanya belum ditentukan) -> 'VESSEL'.
--   - status: nama yang punya suffix "(SCRAP)"/"(Scrap)" -> 'SCRAP' (suffix dibuang dari nama
--     yang disimpan), sisanya -> 'AKTIF'.
--   - vessel_type: TIDAK DIPAKAI (keputusan user 2026-09) -- pengelompokan/chart HANYA pakai
--     fleet_group (nilainya lebih detail dari domain awal TANKER/TUGBOAT/CEMENT CARRIER/OTHERS/
--     TBA yang disebutkan awal: fleet_group asli juga punya BULK CARRIER/TOWING BARGE/OIL BARGE).
--   - alias_name: kolom disiapkan (text[], nullable) TAPI file sumber TIDAK punya data alias
--     sama sekali -- semua baris hasil ekstraksi ini punya alias_name NULL. Isi manual belakangan
--     kalau ditemukan nama lama/alias yang perlu di-map saat pencocokan data Courier/Sea&Air/
--     Borongan (lihat field vessel_name yang tidak cocok = wajib ditandai "perlu diperiksa",
--     BUKAN dibiarkan lewat -- itu bagian dari logic ETL cost-per-vessel, di luar cakupan file
--     SQL ini).

create table if not exists public.master_vessel (
  vessel_id bigint generated always as identity primary key,
  vessel_name text not null unique,
  alias_name text[],
  base text not null,
  fleet_group text not null,
  category text not null check (category in ('VESSEL', 'OTHERS')),
  status text not null default 'AKTIF' check (status in ('AKTIF', 'SCRAP')),
  created_at timestamptz not null default now()
);

alter table public.master_vessel enable row level security;

-- page_key 'reporting_dashboard'/'reporting_cost_per_vessel' BELUM didaftarkan di
-- src/lib/permissions.ts PAGE_REGISTRY saat file ini ditulis -- WAJIB didaftarkan bareng saat
-- halaman React-nya dibuat, kalau tidak has_page_access() selalu false (RLS nge-block semua).
drop policy if exists master_vessel_select on public.master_vessel;
create policy master_vessel_select on public.master_vessel
  for select using (
    public.has_page_access('reporting_dashboard') or public.has_page_access('reporting_cost_per_vessel')
  );

-- Edit master vessel (tambah/koreksi kapal baru) SEMENTARA admin-only -- belum ada halaman
-- admin utk kelola master_vessel di scope ini, jadi digating is_admin() dulu (bukan
-- has_edit_access ke page_key spesifik) supaya tidak ke-lock total kalau ternyata dibutuhkan
-- sebelum UI-nya ada. Longgarkan/pindah ke has_edit_access kalau nanti dibuatkan halaman
-- admin-nya sendiri.
drop policy if exists master_vessel_admin_write on public.master_vessel;
create policy master_vessel_admin_write on public.master_vessel
  for all using (public.is_admin()) with check (public.is_admin());

